#!/usr/bin/env python3
"""Usage: python3 ladder_sqr.py > ladder_sqr.s

The 4-way radix-2^25.5 squaring h = f^2 (given f19 = 19 f), like ladder_mul.py
but with each cross product f_i f_j (i < j) computed once and doubled: 55
VPMULUDQ instead of 100. Coefficients: 2 for i != j, times 2 when i and j are
both odd, times 19 when i + j >= 10 (read from f19).

Unlike ladder_mul.py this ends with a single parallel carry round: the output
limbs are below 2^26 + 2^36 (limb 0: 2^26 + 19 * 2^36) when the input is below
2.01 times the normalized bounds, as `edwards4` requires and handles."""
L = []
acc = [f"%ymm{k}" for k in range(10)]
A, A2, A4, T = "%ymm10", "%ymm11", "%ymm12", "%ymm13"
started = set()
for i in range(10):
    L.append(f"vmovdqa {32 * i}({{f}}), {A}")
    L.append(f"vpaddq {A}, {A}, {A2}")
    if i & 1:
        L.append(f"vpaddq {A2}, {A2}, {A4}")
    for j in range(i, 10):
        k = (i + j) % 10
        if j == i:
            src = A2 if i & 1 else A
        else:
            src = A4 if (i & j & 1) else A2
        mem = f"{32 * j}({{f19}})" if i + j >= 10 else f"{32 * j}({{f}})"
        if k not in started:
            L.append(f"vpmuludq {mem}, {src}, {acc[k]}")
            started.add(k)
        else:
            L += [f"vpmuludq {mem}, {src}, {T}", f"vpaddq {T}, {acc[k]}, {acc[k]}"]
assert started == set(range(10))
for _ in range(1):  # parallel carry round, as in ladder_mul.py
    c, n = "%ymm13", "%ymm14"
    L += [f"vpsrlq $26, {acc[0]}, {c}", f"vpand ({{m}}), {acc[0]}, {acc[0]}"]
    for i in range(1, 10):
        bits, mask = (25, "32({m})") if i & 1 else (26, "({m})")
        L += [f"vpsrlq ${bits}, {acc[i]}, {n}", f"vpand {mask}, {acc[i]}, {acc[i]}",
              f"vpaddq {c}, {acc[i]}, {acc[i]}"]
        c, n = n, c
    L += [f"vpsllq $1, {c}, %ymm12", f"vpsllq $4, {c}, %ymm15",
          f"vpaddq %ymm12, {c}, {c}", f"vpaddq %ymm15, {c}, {c}",
          f"vpaddq {c}, {acc[0]}, {acc[0]}"]
for k in range(10):
    L.append(f"vmovdqa {acc[k]}, {32 * k}({{h}})")
print("# Generated by ladder_sqr.py; do not edit.")
print("\n".join(L))
