#!/usr/bin/env python3
"""Usage: python3 ladder_mul.py > ladder_mul.s

Generates the assembly of `mul` in ladder.rs: a 4-way radix-2^25.5 field
multiplication h = f * g (VPMULUDQ schoolbook, operand scanning) followed by
two parallel carry rounds. With intrinsics, compilers keep the accumulators in
memory or reassociate the sums and spill; here ymm0-9 accumulate limbs
h0..h9, ymm10/ymm11 hold f_i and 2 f_i, and ymm12-15 are temporaries.

Limb k of the product gets f_i * g_j for i + j = k (mod 10), times 2 when i and
j are both odd (radix 2^25.5) and times 19 when i + j >= 10 (2^255 = 19), the
latter read from the precomputed g19 = 19 * g. {m} points at the 26-bit mask,
followed by the 25-bit mask."""
L = []
acc = [f"%ymm{k}" for k in range(10)]
A, A2, T = "%ymm10", "%ymm11", "%ymm12"
for i in range(10):
    L.append(f"vmovdqa {32 * i}({{f}}), {A}")
    if i & 1:
        L.append(f"vpaddq {A}, {A}, {A2}")
    for j in range(10):
        k = (i + j) % 10
        src = A2 if (i & j & 1) else A
        mem = f"{32 * j}({{g19}})" if i + j >= 10 else f"{32 * j}({{g}})"
        if i == 0:
            L.append(f"vpmuludq {mem}, {src}, {acc[k]}")
        else:
            L += [f"vpmuludq {mem}, {src}, {T}", f"vpaddq {T}, {acc[k]}, {acc[k]}"]
for _ in range(2):  # parallel carry round; see carry_round() for the bounds
    c, n = "%ymm13", "%ymm14"
    L += [f"vpsrlq $26, {acc[0]}, {c}", f"vpand ({{m}}), {acc[0]}, {acc[0]}"]
    for i in range(1, 10):
        bits, mask = (25, "32({m})") if i & 1 else (26, "({m})")
        L += [f"vpsrlq ${bits}, {acc[i]}, {n}", f"vpand {mask}, {acc[i]}, {acc[i]}",
              f"vpaddq {c}, {acc[i]}, {acc[i]}"]
        c, n = n, c
    L += [f"vpsllq $1, {c}, %ymm12", f"vpsllq $4, {c}, %ymm15",  # h0 += 19 * c
          f"vpaddq %ymm12, {c}, {c}", f"vpaddq %ymm15, {c}, {c}",
          f"vpaddq {c}, {acc[0]}, {acc[0]}"]
for k in range(10):
    L.append(f"vmovdqa {acc[k]}, {32 * k}({{h}})")
print("# Generated by ladder_mul.py; do not edit.")
print("\n".join(L))
