#!/usr/bin/env python3
"""Usage: python3 base_table.py > base_table.rs

Generates the base point tables of edwards25519, as affine
(y + x, y - x, 2dxy), each coordinate as four little-endian 64-bit limbs
(canonical):
* BASE_TABLE[i][j] = (j + 1) * 256^i * B for i < 32 and j < 8, for the
  constant-time `edwards::mul_base`;
* ODD_MULTIPLES_4WAY[j] = (2j + 1) * B for j < 2^(B_NAF_WIDTH - 2), the
  digits of a width-B_NAF_WIDTH NAF, as the cached points of `edwards4`:
  lanes (L(y - x), L(y + x), -2*121665*xy, 2L) with L = 121666, in radix
  2^25.5 (ten limbs of four lanes), then the same with every limb times 19."""
B_NAF_WIDTH = 6
p = 2**255 - 19
d = -121665 * pow(121666, p - 2, p) % p


def inv(x):
    return pow(x, p - 2, p)


def add(P, Q):
    (x1, y1), (x2, y2) = P, Q
    t = d * x1 * x2 * y1 * y2 % p
    return ((x1 * y2 + x2 * y1) * inv(1 + t) % p, (y1 * y2 + x1 * x2) * inv(1 - t) % p)


def on_curve(P):
    x, y = P
    return (-x * x + y * y - 1 - d * x * x * y * y) % p == 0


by = 4 * inv(5) % p
bx = pow((by * by - 1) * inv(d * by * by + 1), (p + 3) // 8, p)
if (bx * bx - (by * by - 1) * inv(d * by * by + 1)) % p != 0:
    bx = bx * pow(2, (p - 1) // 4, p) % p
if bx & 1:
    bx = p - bx
B = (bx, by)
assert on_curve(B)

limbs = lambda v: [(v >> (64 * i)) & (2**64 - 1) for i in range(4)]


def niels(Q):
    assert on_curve(Q)
    x, y = Q
    xy2d = 2 * d * x * y % p
    # `edwards::select_niels` negates xy2d as 2p - xy2d limb by limb, which
    # needs no borrow when the low limb is at most that of 2p (2^64 - 38).
    assert limbs(xy2d)[0] <= 2**64 - 38
    return limbs((y + x) % p) + limbs((y - x) % p) + limbs(xy2d)


rows = []
P = B
for i in range(32):
    row, Q = [], P
    for j in range(8):
        row.append(niels(Q))
        Q = add(Q, P)
    rows.append(row)
    for _ in range(8):  # P = 256 P
        P = add(P, P)

print("// Generated by base_table.py; do not edit.")
print()
print("/// 32-byte alignment, for tables read as vectors.")
print("#[repr(C, align(32))]")
print("pub(super) struct Aligned<T>(pub(super) T);")
print()
print("/// `BASE_TABLE[i][j]` is (j + 1) 256^i B as (y + x, y - x, 2dxy), affine.")
print("#[rustfmt::skip]")
print("pub(super) static BASE_TABLE: Aligned<[[[u64; 12]; 8]; 32]> = Aligned([")
for row in rows:
    print("    [")
    for entry in row:
        print("        [" + ", ".join("0x%016x" % w for w in entry) + "],")
    print("    ],")
print("]);")
B2 = add(B, B)

LAMBDA = 121666
BITS = [26, 25] * 5


def radix(v):
    v %= p
    out = []
    for bits in BITS:
        out.append(v & ((1 << bits) - 1))
        v >>= bits
    assert v == 0
    return out


def cached4(Q):
    x, y = Q
    lanes = [LAMBDA * (y - x), LAMBDA * (y + x), -2 * 121665 * x * y, 2 * LAMBDA]
    limbs = [radix(v) for v in lanes]  # [lane][limb]
    f4 = [[limbs[lane][i] for lane in range(4)] for i in range(10)]
    f4_19 = [[19 * v for v in limb] for limb in f4]
    return f4, f4_19


entries = []
Q = B
for j in range(1 << (B_NAF_WIDTH - 2)):
    entries.append(cached4(Q))
    Q = add(Q, B2)
print()
print("/// The NAF width of the base point's scalar in `edwards4`.")
print(f"pub(super) const B_NAF_WIDTH: u32 = {B_NAF_WIDTH};")
print()
print("/// `ODD_MULTIPLES_4WAY[j]` is (2j + 1) B, as a cached point of `edwards4`:")
print("/// the ten limbs of four lanes, then the same times 19.")
print("#[rustfmt::skip]")
print(f"pub(super) static ODD_MULTIPLES_4WAY: Aligned<[[[[u64; 4]; 10]; 2]; {len(entries)}]> = Aligned([")
for f4, f4_19 in entries:
    print("    [")
    for part in (f4, f4_19):
        print("        [" + ", ".join("[" + ", ".join("0x%x" % v for v in limb) + "]" for limb in part) + "],")
    print("    ],")
print("]);")
